#!/usr/bin/env node
/**
 * Design token guard.
 *
 * Three checks, each corresponding to a way this codebase has already broken:
 *
 *  1. PHANTOM CLASSES. Roughly sixty Tailwind colour utilities referenced
 *     tokens that were never defined — `text-light-grey`, `bg-brand-gold`,
 *     `border-medium-grey`. Tailwind emits nothing for an unknown token and
 *     reports no error, so the skip-to-content link rendered with no
 *     background, `Card` borders did not render, and `SectionContainer
 *     background="light"` produced a white section. Nothing caught it.
 *
 *  2. RAW HEX. Colour values drifted between tailwind.config.ts, globals.css
 *     and component class strings. The Lumina product page was shipping
 *     `#FF7F50` — CSS "coral" — where the brand coral is `#FF7A5A`.
 *
 *  3. CONTRAST. The business claims accessibility as a value and the site is
 *     moving to dark-first surfaces. Every pair in `contrastPairs` must meet
 *     WCAG AA, and every pair in `prohibitedPairs` must genuinely fail — if a
 *     prohibited pair starts passing, the note explaining it is stale.
 *
 * Run: npm run check:tokens
 */

import { readFileSync } from 'node:fs'
import { globSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..')

const { brand, product, neutral, status, contrastPairs, prohibitedPairs } =
  await import(resolve(ROOT, 'lib/design/tokens.ts'))

/** Tailwind colour token names generated by tailwind.config.ts. */
const VALID_TOKENS = new Set([
  'effuse-slate',
  'effuse-teal',
  'effuse-gold',
  'effuse-off-black',
  'effuse-medium-grey',
  'effuse-light-neutral',
  'effuse-light-grey',
  'effuse-white',
  'lumina-gold',
  'lumina-coral',
  'lumina-teal',
  'lumina-gradient-start',
  'lumina-gradient-end',
  'success',
  'warning',
  'error',
])

/**
 * Token-shaped names that must never reappear. These are the exact phantoms
 * that were live in this repo; listing them explicitly means a copy-paste from
 * an old branch or an old answer fails loudly rather than silently.
 */
const KNOWN_PHANTOMS = [
  'brand-gold',
  'brand-teal-light',
  'brand-teal-dark',
  'slate-grey',
  'off-black',
  'light-grey',
  'medium-grey',
  'sl-blue',
  'sl-red',
  'sl-purple',
  'sl-magenta',
  'sl-bg-dark',
  'sl-bg-light',
]

const UTILITY_PREFIXES =
  'text|bg|border|from|to|via|ring|decoration|outline|fill|stroke|divide|placeholder|accent|caret|shadow'

const SOURCE_GLOBS = [
  'app/**/*.{ts,tsx,css}',
  'components/**/*.{ts,tsx,css}',
  'content/**/*.{ts,tsx}',
  'lib/**/*.{ts,tsx}',
]

const errors = []

function addError(file, line, message) {
  errors.push(`${relative(ROOT, file)}:${line}  ${message}`)
}

// ── 1 & 2: scan source files ────────────────────────────────────────────────
// Node's globSync ignores `absolute: true` here and returns paths relative to
// `cwd`, so resolve them explicitly — the lib/design exclusion below depends on
// matching an absolute path.
const files = SOURCE_GLOBS.flatMap(pattern =>
  globSync(pattern, { cwd: ROOT }).map(file => resolve(ROOT, file))
)

const phantomPattern = new RegExp(
  `(?<![\\w-])(?:[a-z-]+:)*(?:${UTILITY_PREFIXES})-(${KNOWN_PHANTOMS.map(p => p.replace(/-/g, '\\-')).join('|')})(?![\\w-])`,
  'g'
)
const hexPattern = /#[0-9a-fA-F]{3,8}\b/g

for (const file of files) {
  // The token file is the one place allowed to name colours literally.
  if (file.includes('/lib/design/')) continue

  const lines = readFileSync(file, 'utf8').split('\n')
  lines.forEach((text, i) => {
    for (const match of text.matchAll(phantomPattern)) {
      addError(
        file,
        i + 1,
        `phantom token "${match[1]}" — not defined in tailwind.config.ts, so Tailwind emits nothing for "${match[0]}"`
      )
    }
    for (const match of text.matchAll(hexPattern)) {
      addError(
        file,
        i + 1,
        `raw hex ${match[0]} — import from lib/design/tokens.ts, or use a Tailwind class / theme() in CSS`
      )
    }
  })
}

// ── 3: contrast ─────────────────────────────────────────────────────────────
function luminance(hex) {
  const v = hex.replace('#', '')
  const full =
    v.length === 3
      ? v
          .split('')
          .map(c => c + c)
          .join('')
      : v
  const channels = [0, 2, 4].map(i => {
    const c = parseInt(full.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]
}

function contrastRatio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

for (const pair of contrastPairs) {
  const ratio = contrastRatio(pair.foreground, pair.background)
  const required = pair.largeText ? 3 : 4.5
  if (ratio < required) {
    errors.push(
      `contrast  "${pair.name}" is ${ratio.toFixed(2)}:1, needs ${required}:1 ` +
        `(${pair.foreground} on ${pair.background})`
    )
  }
}

for (const pair of prohibitedPairs) {
  const ratio = contrastRatio(pair.foreground, pair.background)
  if (ratio >= 4.5) {
    errors.push(
      `contrast  "${pair.name}" is listed as prohibited but now passes at ` +
        `${ratio.toFixed(2)}:1 — remove it from prohibitedPairs and update the note`
    )
  }
}

// ── report ──────────────────────────────────────────────────────────────────
const tokenCount =
  Object.keys(brand).length +
  Object.keys(product.lumina).length +
  Object.keys(neutral).length +
  Object.keys(status).length

if (errors.length > 0) {
  console.error(`\n✖ ${errors.length} design token problem(s):\n`)
  for (const error of errors) console.error(`  ${error}`)
  console.error(
    `\n  ${VALID_TOKENS.size} valid Tailwind colour tokens are defined in tailwind.config.ts.\n`
  )
  process.exit(1)
}

console.log(
  `✓ design tokens: ${files.length} files scanned, no phantom classes, no raw hex, ` +
    `${contrastPairs.length} contrast pairs pass WCAG AA (${tokenCount} tokens declared)`
)
